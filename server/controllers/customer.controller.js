
import bcrypt from 'bcryptjs';
import Customer from '../models/customer.model.js';
import generateToken from '../utils/generateToken.js';

// Helper function to validate email format using a Regular Expression (Regex).
const isValidEmail = (email) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);


export const registerCustomer = async (req, res) => {
  try {
    // Destructure input fields sent from client in req.body
    const { fullName, email, password, phone } = req.body;

    // Input Validation: Check that required fields exist

    if (!fullName || !email || !password || !phone) {
      // HTTP 400 Bad Request: Used when the client sends incomplete or malformed data.
      return res.status(400).json({ message: 'All fields are required' });
    }

    if (!isValidEmail(email)) {
      return res.status(400).json({ message: 'Invalid email format' });
    }

    if (password.length < 6) {
      return res.status(400).json({ message: 'Password must be at least 6 characters' });
    }

    
    const existingCustomer = await Customer.findOne({ email });
    if (existingCustomer) {
      return res.status(400).json({ message: 'Email already exists' });
    }

    
    // Hashing is a ONE-WAY mathematical transformation. Unlike encryption (which can be decrypted),
    // a hash cannot be converted back to the original plain-text password.

    //  bcrypt.hash(password, 10):
    //  10 is the SALT ROUNDS 
    // - A SALT is a unique random string automatically generated by bcrypt and combined with the password
    //   before hashing. Salt prevents identical passwords from generating identical hashes and protects
    //   against rainbow table attacks.
    const hashedPassword = await bcrypt.hash(password, 10);

    const customer = await Customer.create({
      fullName,
      email,
      password: hashedPassword,
      phone,
    });

    // HTTP 201 Created: Standard HTTP status code for successful creation of a new resource.
    // SECURITY PRACTICE: Never return the password (even hashed) in the HTTP response!
    res.status(201).json({
      message: 'Customer registered successfully',
      customer: {
        fullName: customer.fullName,
        email: customer.email,
        phone: customer.phone,
      },
    });
  } catch (error) {
    // HTTP 500 Internal Server Error: Returned when an unhandled server or database error occurs.
    res.status(500).json({ message: 'Server error' });
  }
};


export const loginCustomer = async (req, res) => {
  try {
    const { email, password } = req.body;
    if (!email || !password) {
      return res.status(400).json({ message: 'Email and password are required' });
    }

    // Find customer by email in MongoDB
    const customer = await Customer.findOne({ email });
    if (!customer) {
      // HTTP 401 Unauthorized: Returned when authentication fails.
      return res.status(401).json({ message: 'Invalid Credentials' });
    }

    // Compares the plain-text password entered by the user during login with the hashed password stored in MongoDB.
    // Bcrypt hashes the entered password using the salt embedded in the stored hash and compares the result.
    const isMatch = await bcrypt.compare(password, customer.password);
    if (!isMatch) {
      return res.status(401).json({ message: 'Invalid Credentials' });
    }

    // CONCEPT: JWT TOKEN GENERATION
    // generateToken creates a signed JSON Web Token (JWT) containing the user's MongoDB `_id`.
    const token = generateToken(customer._id);

    // CONCEPT: HTTPONLY COOKIE & AUTHENTICATION
    // `res.cookie()` attaches a `Set-Cookie` header to the HTTP response.
    // Properties:
    //   - `httpOnly: true`: Prevents client-side JavaScript (`document.cookie`) from accessing the cookie.
    //     This protects against Cross-Site Scripting (XSS) attacks.
    //   - `sameSite: 'lax'`: Helps protect against Cross-Site Request Forgery (CSRF) attacks.
    //   - `secure: false`: Allows HTTP in local development (set to true in HTTPS production).
    //   - `maxAge`: Cookie expiration time in milliseconds (24 hours).
    res.cookie('token', token, {
      httpOnly: true,
      sameSite: 'lax',
      secure: false,
      path: '/',
      maxAge: 24 * 60 * 60 * 1000,  //milisec
    });

    // HTTP 200 OK: Standard successful HTTP response.
    res.status(200).json({
      message: 'Login successful',
      customer: {
        fullName: customer.fullName,
        email: customer.email,
        phone: customer.phone,
      },
    });
  } catch (error) {
    res.status(500).json({ message: 'Server error' });
  }
};

// 3. GET CURRENT CUSTOMER CONTROLLER (PROTECTED PROFILE)
export const getCurrentCustomer = async (req, res) => {
  // `req.user` was fetched from MongoDB and attached to `req` by `authMiddleware`
  if (!req.user) {
    return res.status(401).json({ message: 'Not authorized' });
  }

  const { fullName, email, phone } = req.user;
  res.status(200).json({
    fullName,
    email,
    phone,
  });
};


export const logoutCustomer = (req, res) => {
  // WHAT IT DOES: `res.clearCookie()` instructs the browser to delete the `token` cookie.
  // WHY IT IS NEEDED: Invalidates the user session on the client side.
  res.clearCookie('token', {
    httpOnly: true,
    sameSite: 'lax',
    secure: false,
    path: '/',
  });
  res.status(200).json({ message: 'Logged out successfully' });
};
